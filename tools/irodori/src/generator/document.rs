const CASSANDRA_SCHEMA: &str = r#"
CREATE KEYSPACE IF NOT EXISTS samples
  WITH replication = {'class': 'SimpleStrategy', 'replication_factor': 1};
USE samples;

DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders_by_customer;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS customers;

CREATE TABLE customers (
  id int PRIMARY KEY, name text, email text, country_code text, tier text,
  credit_limit decimal, is_active boolean, signup_source text,
  created_at timestamp, metadata text
);
CREATE TABLE products (
  id int PRIMARY KEY, sku text, name text, category text, price decimal,
  weight_kg decimal, in_stock boolean, supplier text, released_on date, tags text
);
CREATE TABLE orders (
  id int PRIMARY KEY, customer_id int, status text, channel text, currency text,
  subtotal decimal, tax decimal, total decimal,
  ordered_at timestamp, shipped_at timestamp, note text
);
CREATE TABLE orders_by_customer (
  customer_id int, ordered_at timestamp, id int, status text, channel text,
  currency text, subtotal decimal, tax decimal, total decimal,
  shipped_at timestamp, note text,
  PRIMARY KEY ((customer_id), ordered_at, id)
) WITH CLUSTERING ORDER BY (ordered_at DESC, id ASC);
CREATE TABLE order_items (
  order_id int, id int, product_id int, quantity int,
  unit_price decimal, discount_rate decimal, line_total decimal,
  PRIMARY KEY ((order_id), id)
);
CREATE TABLE events (
  customer_id int, occurred_at timestamp, id int, event_type text,
  session_id text, device text, duration_ms int, payload text,
  PRIMARY KEY ((customer_id), occurred_at, id)
) WITH CLUSTERING ORDER BY (occurred_at DESC, id ASC);
"#;
