// --- MongoDB ----------------------------------------------------------------
// order_items are embedded in their order, which is the document shape; the
// lines are all still there, inside the arrays.
{
  const iso = (msValue) => `ISODate("${new Date(Math.floor(msValue / 1000) * 1000).toISOString()}")`
  const s = [
    `// Irodori Table sample data — MongoDB.`,
    `// Generated by generator/generate.mjs (seed=${meta.SEED}, scale=${meta.SCALE}).`,
    `// Do not edit by hand; re-run the generator instead.`,
    `//`,
    `// order_items are embedded in orders, so this is ${data.orders.length} order`,
    `// documents holding ${data.orderItems.length} lines between them.`,
    `const db = db.getSiblingDB("samples");`,
    `db.customers.drop(); db.products.drop(); db.orders.drop(); db.events.drop();`,
  ]
  const many = (coll, rows, toDoc) => {
    const out = []
    for (let i = 0; i < rows.length; i += 100) {
      out.push(`db.${coll}.insertMany([\n` +
        rows.slice(i, i + 100).map((r) => '  ' + toDoc(r)).join(',\n') + '\n]);')
    }
    return out.join('\n')
  }
  s.push(many('customers', data.customers, (c) => JSON.stringify({
    _id: c.id, name: c.name, email: c.email, country_code: c.country_code, tier: c.tier,
    credit_limit: c.credit_limit, is_active: c.is_active, signup_source: c.signup_source,
    metadata: c.metadata,
  }).replace(/}$/, `,"created_at":${iso(c.created_ms)}}`)))
  s.push(many('products', data.products, (p) => JSON.stringify({
    _id: p.id, sku: p.sku, name: p.name, category: p.category, price: p.price,
    weight_kg: p.weight_kg, in_stock: p.in_stock, supplier: p.supplier,
    released_on: p.released_on, tags: p.tags,
  })))
  s.push(many('orders', data.orders, (o) => {
    const doc = JSON.stringify({
      _id: o.id, customer_id: o.customer_id, status: o.status, channel: o.channel,
      currency: o.currency, subtotal: o.subtotal, tax: o.tax, total: o.total,
      note: o.note,
      items: o.items.map((i) => ({
        product_id: i.product_id, quantity: i.quantity, unit_price: i.unit_price,
        discount_rate: i.discount_rate, line_total: i.line_total,
      })),
    })
    const shipped = o.shipped_at
      ? `ISODate("${o.shipped_at.replace(' ', 'T')}.000Z")`
      : 'null'
    return doc.replace(/}$/, `,"ordered_at":${iso(o.ordered_ms)},"shipped_at":${shipped}}`)
  }))
  s.push(many('events', data.events, (e) => JSON.stringify({
    _id: e.id, customer_id: e.customer_id, event_type: e.event_type,
    session_id: e.session_id, device: e.device, duration_ms: e.duration_ms,
    payload: e.payload,
  }).replace(/}$/, `,"occurred_at":${iso(e.occurred_ms)}}`)))
  s.push(`
db.customers.createIndex({ country_code: 1 });
db.customers.createIndex({ tier: 1, credit_limit: -1 });
db.products.createIndex({ sku: 1 }, { unique: true });
db.orders.createIndex({ customer_id: 1, ordered_at: -1 });
db.orders.createIndex({ "items.product_id": 1 });
db.events.createIndex({ customer_id: 1, occurred_at: -1 });
`)
  write('mongodb/01_samples.js', s.join('\n'))
}

