#!/usr/bin/env node
// Regenerate every `<engine>/01_samples.*` seed in this repo.
//
//   node generator/generate.mjs
//   SCALE=0.1 node generator/generate.mjs   # bigger, if you want it
//
// The seeds are committed rather than generated at run time on purpose: an
// engine's container init hook loads them on first boot, so `compose up` gives a
// populated database with no extra step. That only works if the file is already
// there, which is also why the default scale is small — these are meant to be
// readable and to boot in seconds, not to be a benchmark. The irodori-table
// database playground is where the 196k-row version lives.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build, meta, N } from './core.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const data = build()

const write = (rel, body) => {
  const path = join(ROOT, rel)
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, body.endsWith('\n') ? body : body + '\n')
  const lines = body.trim().split('\n').length
  console.log(`  ${rel.padEnd(34)} ${String(lines).padStart(6)} lines`)
}

// --- literal helpers --------------------------------------------------------
const sq = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`)
const num = (v) => (v === null || v === undefined ? 'NULL' : String(v))
const bool = (v, style = 'sql') =>
  style === 'int' ? (v ? '1' : '0') : v ? 'TRUE' : 'FALSE'
const json = (v) => sq(JSON.stringify(v))

// INSERT statements in batches, so a seed file stays diffable and no single
// statement grows past what an engine will parse.
const inserts = (table, columns, rows, toValues, batch = 100) => {
  const out = []
  for (let i = 0; i < rows.length; i += batch) {
    const chunk = rows.slice(i, i + batch)
    out.push(
      `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n` +
        chunk.map((r) => '  (' + toValues(r).join(', ') + ')').join(',\n') +
        ';',
    )
  }
  return out.join('\n')
}

