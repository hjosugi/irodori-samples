  `-- Irodori Table sample data — ${engine}.\n` +
  `-- Generated by generator/generate.mjs (seed=${meta.SEED}, scale=${meta.SCALE}).\n` +
  `-- Do not edit by hand; re-run the generator instead.\n` +
  `-- ${N.customers} customers, ${N.products} products, ${data.orders.length} orders, ` +
  `${data.orderItems.length} order lines, ${data.events.length} events.\n`

console.log(`seed=${meta.SEED} scale=${meta.SCALE}`)

