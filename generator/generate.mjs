  // Oracle has no multi-row VALUES; INSERT ALL is the idiomatic bulk form.
  const oraTs = (v) => (v === null ? 'NULL' : `TO_TIMESTAMP(${sq(v)}, 'YYYY-MM-DD HH24:MI:SS')`)
  const oraDate = (v) => `TO_DATE(${sq(v)}, 'YYYY-MM-DD')`
  const insertAll = (table, columns, rows, toValues, batch = 50) => {
    const out = []
    for (let i = 0; i < rows.length; i += batch) {
      const chunk = rows.slice(i, i + batch)
      out.push('INSERT ALL\n' +
        chunk.map((r) => `  INTO ${table} (${columns.join(', ')}) VALUES (${toValues(r).join(', ')})`).join('\n') +
        '\nSELECT * FROM dual;')
    }
    return out.join('\n')
  }
